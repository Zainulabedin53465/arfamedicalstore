import fs from 'node:fs';

function parseCSV(t) {
  const rows = []; let row = [], cur = '', inQ = false;
  for (let i = 0; i < t.length; i++) {
    const c = t[i];
    if (inQ) {
      if (c === '"' && t[i + 1] === '"') { cur += '"'; i++; }
      else if (c === '"') inQ = false;
      else cur += c;
    } else if (c === '"') inQ = true;
    else if (c === ',') { row.push(cur); cur = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && t[i + 1] === '\n') i++;
      row.push(cur); cur = '';
      if (row.some((x) => x !== '')) rows.push(row);
      row = [];
    } else cur += c;
  }
  if (cur !== '' || row.length) { row.push(cur); if (row.some((x) => x !== '')) rows.push(row); }
  return rows;
}

const { PRODUCTS } = await import(process.cwd() + '/src/config/products.js');
const known = new Set(PRODUCTS.map((p) => p.id));
const rows = parseCSV(fs.readFileSync('catalog.csv', 'utf8').replace(/^\uFEFF/, ''));
const head = rows.shift().map((h) => h.trim().toLowerCase());
const col = (n) => head.indexOf(n);
if (['id', 'price', 'availability', 'image'].some((n) => col(n) < 0)) {
  console.error('catalog.csv is missing a required column.'); process.exit(1);
}

const PRICES = {}, STOCK = {}, IMAGES = {}, problems = [];
for (const r of rows) {
  const id = (r[col('id')] || '').trim();
  if (!known.has(id)) { problems.push(`Unknown id "${id}" (ignored)`); continue; }

  const price = (r[col('price')] || '').trim().replace(/^₹/, '').replace(/,/g, '');
  if (price !== '') {
    const n = Number(price);
    if (!Number.isFinite(n) || n <= 0 || n > 100000) problems.push(`${id}: bad price "${price}" (ignored)`);
    else PRICES[id] = Math.round(n * 100) / 100;
  }

  const av = (r[col('availability')] || '').trim().toLowerCase();
  if (av !== '') {
    if (av === 'in_stock' || av === 'out_of_stock') STOCK[id] = av;
    else problems.push(`${id}: availability must be in_stock or out_of_stock (ignored)`);
  }

  const img = (r[col('image')] || '').trim();
  if (img !== '') {
    let ok = false;
    try { ok = new URL(img).protocol === 'https:'; } catch { /* invalid */ }
    if (ok) IMAGES[id] = img; else problems.push(`${id}: image must be a full https:// URL (ignored)`);
  }
}

const out = `// Generated by scripts/catalog-import.mjs from catalog.csv. You can also edit by hand.
// PRICES: rupees. STOCK: 'in_stock' | 'out_of_stock'. IMAGES: https URLs only.
export const PRICES = ${JSON.stringify(PRICES, null, 2)};
export const STOCK = ${JSON.stringify(STOCK, null, 2)};
export const IMAGES = ${JSON.stringify(IMAGES, null, 2)};
`;
fs.writeFileSync('src/config/catalogData.js', out);
console.log(`Imported: ${Object.keys(PRICES).length} prices, ${Object.keys(STOCK).length} stock flags, ${Object.keys(IMAGES).length} images`);
problems.forEach((p) => console.log('WARNING:', p));
